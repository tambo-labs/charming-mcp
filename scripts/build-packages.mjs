function applyReadmeBlocks(source) {
  let out = source;
  for (const [name, body] of Object.entries(README_BLOCKS)) {
    const open = `<!-- generated:${name} -->`;
    const close = `<!-- /generated:${name} -->`;
    const start = out.indexOf(open);
    const end = out.indexOf(close);
    const opens = out.split(open).length - 1;
    const closes = out.split(close).length - 1;
    if (opens !== 1 || closes !== 1) {
      fail(`README.md must hold exactly one ${open} block (found ${opens} open, ${closes} close)`);
      continue;
    }
    if (start === -1 || end === -1 || end < start) {
      fail(`README.md is missing the ${open} to ${close} block`);
      continue;
    }
    out = `${out.slice(0, start)}${open}\n${body}\n${close}${out.slice(end + close.length)}`;
  }
  return out;
}

