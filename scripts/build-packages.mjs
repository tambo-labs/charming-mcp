#!/usr/bin/env node
// Generates every platform adapter in this repository from canonical/.
//
//   node scripts/build-packages.mjs           write the adapters
//   node scripts/build-packages.mjs --check   fail if anything drifted
//
// Canonical inputs (hand-edited): canonical/facts.json, SKILL.md, AGENTS.md,
// .cursor/rules/charming.mdc, charming-icon.png, canonical/assets/.
// Everything this script writes is generated; see DISTRIBUTION.md.

import { createHash } from 'node:crypto';
import { existsSync, mkdirSync, readFileSync, readdirSync, statSync, writeFileSync } from 'node:fs';
import { dirname, join, relative, resolve } from 'node:path';

const ROOT = resolve(import.meta.dirname, '..');
const CHECK = process.argv.includes('--check');

const read = (p) => readFileSync(join(ROOT, p), 'utf8');
const readBytes = (p) => readFileSync(join(ROOT, p));
const facts = JSON.parse(read('canonical/facts.json'));

const BANNER = '<!-- Generated by scripts/build-packages.mjs from canonical/. Do not edit. -->';
const MCP = facts.endpoints.mcp;
const TOOL_NAMES = facts.tools.map((t) => t.name);

const canonicalSkill = read('SKILL.md');
const canonicalAgents = read('AGENTS.md');
const canonicalRule = read('.cursor/rules/charming.mdc');

const json = (value) => `${JSON.stringify(value, null, 2)}\n`;

const problems = [];
const fail = (message) => problems.push(message);

/** Insert the generated banner after YAML frontmatter, which must stay first. */
function withBanner(markdown) {
  if (!markdown.startsWith('---\n')) return `${BANNER}\n\n${markdown}`;
  const end = markdown.indexOf('\n---\n', 3);
  const head = markdown.slice(0, end + 5);
  return `${head}\n${BANNER}\n${markdown.slice(end + 5)}`;
}

function skillFor(platform) {
  let body = withBanner(canonicalSkill);
  const notePath = `canonical/platform-notes/${platform}.md`;
  if (existsSync(join(ROOT, notePath))) {
    const note = read(notePath).replaceAll('{{mcpEndpoint}}', MCP);
    body = `${body.trimEnd()}\n\n${note.trimStart()}`;
  }
  return body;
}

const author = {
  name: facts.product.publisher.name,
  url: facts.product.publisher.org,
};

function packageReadme(platform, installSteps) {
  return [
    BANNER,
    '',
    `# Charming for ${platform}`,
    '',
    facts.product.longDescription,
    '',
    '## Install',
    '',
    installSteps.trim(),
    '',
    '## What it ships',
    '',
    `- The Charming MCP server at \`${MCP}\`.`,
    '- The canonical `charming` skill: the MCP-first authoring workflow and the app contract.',
    '',
    `Full authoring guide: <${facts.urls.llmsFull}>. Published by ${facts.product.publisher.name} (<${facts.product.publisher.url}>).`,
    '',
  ].join('\n');
}

