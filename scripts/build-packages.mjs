#!/usr/bin/env node
// Generates every platform adapter in this repository from canonical/.
//
//   node scripts/build-packages.mjs            write the adapters
//   node scripts/build-packages.mjs --check    fail if anything drifted
//   node scripts/build-packages.mjs --release  stamp the release marker at the current version
//
// Canonical inputs (hand-edited): canonical/facts.json, SKILL.md, AGENTS.md,
// .cursor/rules/charming.mdc, charming-icon.png, canonical/assets/.
// Everything this script writes is generated; see DISTRIBUTION.md.

import { createHash } from 'node:crypto';
import { existsSync, lstatSync, mkdirSync, readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { dirname, join, relative, resolve, sep } from 'node:path';

const ROOT = resolve(import.meta.dirname, '..');
const CHECK = process.argv.includes('--check');
const RELEASE = process.argv.includes('--release');

const read = (p) => readFileSync(join(ROOT, p), 'utf8');
const readBytes = (p) => readFileSync(join(ROOT, p));

/** A malformed canonical input cannot be reported as drift; nothing downstream is meaningful. */
function die(message) {
  console.error(`canonical input is unusable: ${message}`);
  process.exit(1);
}

let facts;
try {
  facts = JSON.parse(read('canonical/facts.json'));
} catch (error) {
  die(`canonical/facts.json is not valid JSON (${error.message})`);
}

validateFacts(facts);

/**
 * Every value below is hand-edited and flows into published packages, so a typo
 * must stop the run rather than reach a template as `undefined`.
 */
function validateFacts(f) {
  const problems = [];
  const req = (path, type) => {
    const value = path.split('.').reduce((acc, key) => (acc == null ? acc : acc[key]), f);
    const actual = Array.isArray(value) ? 'array' : typeof value;
    if (value == null || actual !== type) problems.push(`${path} must be a ${type} (got ${actual})`);
    return value;
  };

  for (const path of [
    'product.name',
    'product.slug',
    'product.shortDescription',
    'product.packageDescription',
    'product.longDescription',
    'product.category',
    'product.brandColor',
    'product.license',
    'product.publisher.name',
    'product.publisher.url',
    'product.publisher.org',
    'version',
    'endpoints.mcp',
    'endpoints.chatgptMcp',
    'marketplace.name',
    'marketplace.displayName',
    'marketplace.owner.name',
    'assets.icon',
    'assets.animatedLogo',
  ]) {
    req(path, 'string');
  }
  for (const path of ['product.keywords', 'defaultPrompts', 'clients', 'tools', 'branding.forbidden', 'branding.allowedTokens', 'branding.exemptFiles', 'checks.allowedIdentifiers', 'checks.fixtureFiles', 'ownedHosts', 'externalHosts']) {
    req(path, 'array');
  }
  req('urls', 'object');

  for (const [i, client] of (f.clients ?? []).entries()) {
    if (!client?.label) problems.push(`clients[${i}].label is missing`);
    if (!f.endpoints?.[client?.endpoint]) {
      problems.push(`clients[${i}].endpoint "${client?.endpoint}" is not a key of endpoints`);
    }
  }
  for (const [i, tool] of (f.tools ?? []).entries()) {
    if (!tool?.name || !tool?.summary) problems.push(`tools[${i}] needs both name and summary`);
  }

  // An endpoint or asset that points off-repo would publish something we do not control.
  const hostOf = (url) => {
    try {
      const parsed = new URL(url);
      return parsed.protocol === 'https:' ? parsed.hostname : null;
    } catch {
      return null;
    }
  };
  for (const [key, url] of Object.entries(f.endpoints ?? {})) {
    if (!f.ownedHosts?.includes(hostOf(url))) problems.push(`endpoints.${key} must be https on an owned host: ${url}`);
  }
  const allowedUrlHosts = [...(f.ownedHosts ?? []), ...(f.externalHosts ?? [])];
  for (const [key, url] of Object.entries(f.urls ?? {})) {
    if (!allowedUrlHosts.includes(hostOf(url))) problems.push(`urls.${key} must be https on a declared host: ${url}`);
  }
  for (const [key, rel] of Object.entries(f.assets ?? {})) {
    const target = resolve(ROOT, String(rel));
    if (!target.startsWith(ROOT + sep)) problems.push(`assets.${key} escapes the repository: ${rel}`);
  }

  if (problems.length > 0) die(`\n  - ${problems.join('\n  - ')}`);
}

