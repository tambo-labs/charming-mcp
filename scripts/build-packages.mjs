function emit(rel, body) {
  const target = join(ROOT, rel);
  const current = existsSync(target) ? readFileSync(target) : null;
  const next = Buffer.isBuffer(body) ? body : Buffer.from(body, 'utf8');
  if (current && current.equals(next)) return;
  if (CHECK) {
    fail(current ? `${rel} is out of date. Run: node scripts/build-packages.mjs` : `${rel} is missing`);
    return;
  }
  mkdirSync(dirname(target), { recursive: true });
  writeFileSync(target, next);
  written.push(rel);
}

for (const [rel, body] of generatedText) emit(rel, body);
for (const [rel, body] of generatedBinary) emit(rel, body);

