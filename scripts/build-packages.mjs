for (const [marketplaceRel, pluginManifest] of Object.entries(MARKETPLACE_MANIFEST)) {
  const catalog = JSON.parse(ROOT_FILES[marketplaceRel]);
  if (!/^[a-z0-9-]+$/.test(catalog.name)) fail(`${marketplaceRel}: marketplace name must be kebab-case`);
  for (const entry of catalog.plugins) {
    if (!/^[a-z0-9-]+$/.test(entry.name)) fail(`${marketplaceRel}: plugin name ${entry.name} must be kebab-case`);
    const source = typeof entry.source === 'string' ? entry.source : entry.source.path;
    if (!source.startsWith('./')) fail(`${marketplaceRel}: source ${source} must start with ./`);
    const dir = join(ROOT, source);
    if (!existsSync(dir) || !lstatSync(dir).isDirectory()) {
      fail(`${marketplaceRel}: source ${source} is not a directory`);
      continue;
    }
    if (!existsSync(join(dir, pluginManifest))) {
      fail(`${marketplaceRel}: ${source} is missing ${pluginManifest}`);
    }
  }
}

// The canonical skill and rule must carry the frontmatter every host requires.
for (const [label, body] of [
  ['SKILL.md', canonicalSkill],
  ['.cursor/rules/charming.mdc', canonicalRule],
]) {
  const end = frontmatterEnd(body);
  if (end === -1) {
    fail(`${label}: YAML frontmatter is missing or never closed`);
    continue;
  }
  if (!/\ndescription:\s*\S/.test(body.slice(0, end))) fail(`${label}: frontmatter needs a description`);
}
if (!/\nname:\s*charming\b/.test(canonicalSkill.slice(0, 200))) {
  fail('SKILL.md: frontmatter name must be "charming"');
}

// ---------------------------------------------------------------------------

// Settled last, and only when asked: a run that reports problems must not move
// the release marker, and an ordinary regenerate must not either.
if (!lock && CHECK) {
  fail(`${VERSION_LOCK} is missing. Run: node scripts/build-packages.mjs --release`);
}
if (problems.length === 0 && (RELEASE || !lock)) {
  const desiredLock = json({ version: facts.version, canonicalInputs });
  const lockPath = join(ROOT, VERSION_LOCK);
  if ((existsSync(lockPath) ? readFileSync(lockPath, 'utf8') : null) !== desiredLock) {
    if (CHECK) {
      fail(`${VERSION_LOCK} is out of date. Run: node scripts/build-packages.mjs --release`);
    } else {
      mkdirSync(dirname(lockPath), { recursive: true });
      writeFileSync(lockPath, desiredLock);
      written.push(VERSION_LOCK);
    }
  }
}

if (problems.length > 0) {
  console.error(`${problems.length} problem(s):`);
  for (const p of problems) console.error(`  - ${p}`);
  process.exit(1);
}

