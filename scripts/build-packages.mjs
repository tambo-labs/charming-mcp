// Fact checks over every text file in the repository

const TEXT_EXTENSIONS = new Set(['.md', '.mdc', '.json', '.txt', '.toml', '.yml', '.yaml', '.mjs', '.svg']);
const SKIP_DIRS = new Set(['.git', 'node_modules']);

/** Files whose text the fact checks read. Symlinks are excluded and reported separately. */
function allFiles(dir = ROOT) {
  const out = [];
  for (const entry of readdirSync(dir, { withFileTypes: true })) {
    if (SKIP_DIRS.has(entry.name)) continue;
    const full = join(dir, entry.name);
    if (entry.isSymbolicLink()) out.push({ path: full, symlink: true });
    else if (entry.isDirectory()) out.push(...allFiles(full));
    else out.push({ path: full, symlink: false });
  }
  return out;
}

const REPO_FILES = allFiles();
// Extensionless files carry text too, and the scans would otherwise skip them.
const TEXT_NAMES = new Set(['LICENSE', 'NOTICE', '.gitattributes', '.gitignore']);
const isTextFile = (path) => {
  const name = path.slice(path.lastIndexOf(sep) + 1);
  return TEXT_NAMES.has(name) || TEXT_EXTENSIONS.has(name.slice(name.lastIndexOf('.')));
};

const KNOWN_URLS = new Set([...Object.values(facts.endpoints), ...Object.values(facts.urls)]);
const ALLOWED_IDENTIFIERS = new Set(facts.checks.allowedIdentifiers);
const ALLOWED_BRAND_TOKENS = facts.branding.allowedTokens;
const BRANDING_EXEMPT = new Set(facts.branding.exemptFiles);
// Files that hold deliberate counter-examples: the drift fixtures the checker
// is tested against, which must not be read as claims about the product.
const FIXTURE_FILES = new Set(facts.checks.fixtureFiles);
// Built from facts.ownedHosts so adding a host cannot silently skip the scan.
const OWNED_HOST = new RegExp(
  `https://(?:${facts.ownedHosts.map((h) => h.replaceAll('.', '\\.')).join('|')})[^\\s"'\`)\\]<>,]*`,
  'g',
);
// An identifier inside any code span or fenced block is a claim about the tool
// surface; the same words in English prose or a YAML key are not.
const CODE_SPAN = /`([^`\n]+)`/g;
const FENCED_BLOCK = /^```[^\n]*\n([\s\S]*?)^```/gm;
const SNAKE_IDENTIFIER = /\b[a-z][a-z0-9]*(?:_[a-z0-9]+)+\b/g;

for (const { path: file, symlink } of REPO_FILES) {
  const rel = relative(ROOT, file);
  if (symlink) {
    fail(`${rel}: symlink. Packages must be self-contained, so every file must be a real file`);
    continue;
  }
  if (!isTextFile(file)) continue;
  if (FIXTURE_FILES.has(rel)) continue;
  const body = readFileSync(file, 'utf8');
  const isFacts = rel === 'canonical/facts.json';
  const isMarkdown = rel.endsWith('.md') || rel.endsWith('.mdc');

  for (const match of body.matchAll(OWNED_HOST)) {
    // Trailing sentence punctuation belongs to the prose, not the URL.
    const url = match[0].replace(/\.git$/, '').replace(/[.,;:!?)\]]+$/, '');
    if (!KNOWN_URLS.has(url) && !KNOWN_URLS.has(`${url}/`)) {
      fail(`${rel}: URL ${url} is not declared in canonical/facts.json`);
    }
  }

  if (!isFacts && !BRANDING_EXEMPT.has(rel)) {
    let stripped = body;
    for (const token of ALLOWED_BRAND_TOKENS) stripped = stripped.replaceAll(token, '');
    for (const word of facts.branding.forbidden) {
      const hit = new RegExp(word, 'i').exec(stripped);
      if (hit) fail(`${rel}: stale branding "${hit[0]}" (allowed only as ${ALLOWED_BRAND_TOKENS.join(', ')})`);
    }
  }

  // Qualifiers are allowed between the count and the noun ("21 MCP tools").
  for (const match of body.matchAll(/\b(\d+)\s+(?:[A-Za-z][\w-]*\s+){0,2}tools\b/g)) {
    if (Number(match[1]) !== facts.tools.length) {
      fail(`${rel}: says "${match[0]}" but canonical/facts.json declares ${facts.tools.length}`);
    }
  }

  if (isMarkdown) {
    const codeText = [
      ...[...body.matchAll(CODE_SPAN)].map((m) => m[1]),
      ...[...body.matchAll(FENCED_BLOCK)].map((m) => m[1]),
    ];
    for (const chunk of codeText) {
      for (const match of chunk.matchAll(SNAKE_IDENTIFIER)) {
        const name = match[0];
        if (TOOL_NAMES.includes(name) || ALLOWED_IDENTIFIERS.has(name)) continue;
        fail(`${rel}: \`${name}\` is not a Charming tool. Add it to facts.tools or checks.allowedIdentifiers`);
      }
    }
  }
}

// A package must contain exactly its generated files. Byte parity alone only
